package com.ironlogic.veyra.ui.tokens

import androidx.compose.ui.unit.dp

/**
 * Shared spacing scale.
 *
 * These are foundational layout increments, not measurements for any
 * specific phone or tablet screen. Screen specifications take precedence.
 */
object VeyraSpacing {
    val xxs = 4.dp
    val xs = 8.dp
    val sm = 12.dp
    val md = 16.dp
    val lg = 20.dp
    val xl = 24.dp
    val xxl = 32.dp
    val xxxl = 40.dp
    val huge = 48.dp
}
